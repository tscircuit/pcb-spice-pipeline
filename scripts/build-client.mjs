import {writeFile, rm} from 'node:fs/promises'
import {build} from 'esbuild'
import {fileURLToPath} from 'node:url'

// Bundle browser code as data at build time. Reports never need the source tree
// or Function.toString(), whose output can contain transpiler closure helpers.
if(process.argv.includes('--clean')) await rm(new URL('../dist/',import.meta.url),{recursive:true,force:true})
const {outputFiles}=await build({entryPoints:[fileURLToPath(new URL('../src/viewer-client.ts',import.meta.url))],
  absWorkingDir:fileURLToPath(new URL('../',import.meta.url)),bundle:true,write:false,format:'iife',globalName:'Viewer',target:'es2023'})
const client='function(){'+outputFiles[0].text+';Viewer.viewerClient();}'
await writeFile(new URL('../src/viewer-client.generated.ts',import.meta.url),
  '// Generated by scripts/build-client.mjs\nexport const browserClient = '+JSON.stringify(client)+'\n')
